// Extracts the province map and the yearly province sales from assets/ceo-dashboard.js so the user panel can show a
// visitor's own area without loading the whole CEO dashboard. Run: node tools/build_area_data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lines = fs.readFileSync(path.join(root, 'assets', 'ceo-dashboard.js'), 'utf8').split(/\r?\n/);
const take = (name) => {
  const line = lines.find((l) => l.trimStart().startsWith('const ' + name + ' ='));
  if (!line) throw new Error('missing ' + name);
  return Function('return ' + line.replace(/^\s*const \w+ =\s*/, '').replace(/;\s*$/, ''))();
};
const svg = take('svgMarkup');
const rows = take('sourceRows');
const isoToProvince = take('isoToProvince');
const years = take('years');
fs.writeFileSync(path.join(root, 'assets', 'iran-map.svg'), svg);
fs.writeFileSync(path.join(root, 'assets', 'area-data.js'),
  '// Generated by tools/build_area_data.mjs from assets/ceo-dashboard.js; do not edit by hand.\n' +
  'window.MS_AREA = ' + JSON.stringify({ years, isoToProvince, rows }) + ';\n');
console.log(JSON.stringify({ svgBytes: svg.length, rows: rows.length, years }));
